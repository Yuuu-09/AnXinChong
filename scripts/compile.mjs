import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import solc from 'solc';

const require = createRequire(import.meta.url);
const root = path.resolve(import.meta.dirname, '..');
const sources = {};
for (const entry of [
  'contracts/src/AnXinChongVault.sol',
  'contracts/src/AnXinChongFactory.sol',
  'contracts/src/AnXinChongUserRegistry.sol',
  'contracts/src/libraries/SettlementMath.sol',
  'contracts/test/mocks/MockUSDC.sol',
]) {
  sources[entry] = { content: fs.readFileSync(path.join(root, entry), 'utf8') };
}
const settings = {
  optimizer: { enabled: true, runs: 200 },
  viaIR: true,
  evmVersion: 'osaka',
  outputSelection: {
    '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'metadata'] },
  },
};
const output = JSON.parse(
  solc.compile(JSON.stringify({ language: 'Solidity', sources, settings }), {
    import(importPath) {
      try {
        const file = importPath.startsWith('@')
          ? require.resolve(importPath)
          : path.join(root, importPath);
        return { contents: fs.readFileSync(file, 'utf8') };
      } catch {
        return { error: `Import not found: ${importPath}` };
      }
    },
  }),
);
for (const diagnostic of output.errors ?? []) console.error(diagnostic.formattedMessage);
if (output.errors?.some((e) => e.severity === 'error')) process.exit(1);
fs.mkdirSync(path.join(root, 'contracts/out/js'), { recursive: true });
for (const file of Object.values(output.contracts))
  for (const [name, artifact] of Object.entries(file)) {
    fs.writeFileSync(
      path.join(root, `contracts/out/js/${name}.json`),
      JSON.stringify(artifact, null, 2) + '\n',
    );
  }
const vault = output.contracts['contracts/src/AnXinChongVault.sol'].AnXinChongVault;
const factory = output.contracts['contracts/src/AnXinChongFactory.sol'].AnXinChongFactory;
const mock = output.contracts['contracts/test/mocks/MockUSDC.sol'].MockUSDC;
const registry =
  output.contracts['contracts/src/AnXinChongUserRegistry.sol'].AnXinChongUserRegistry;
const generated = `// Generated by scripts/compile.mjs; do not edit.\nexport const registryAbi = ${JSON.stringify(registry.abi)} as const;\nexport const factoryAbi = ${JSON.stringify(factory.abi)} as const;\nexport const vaultAbi = ${JSON.stringify(vault.abi)} as const;\nexport const tokenAbi = ${JSON.stringify(mock.abi)} as const;\n`;
for (const [name, artifact] of [
  ['Vault', vault],
  ['Factory', factory],
  ['UserRegistry', registry],
]) {
  const size = artifact.evm.deployedBytecode.object.length / 2;
  if (size > 24576) throw new Error(`${name} exceeds the EIP-170 runtime size limit: ${size}`);
  console.log(`${name} runtime: ${size} bytes`);
}
const target = path.join(root, 'web/src/generated/abi.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== generated)
    throw new Error('Generated ABI is stale. Run pnpm compile.');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, generated);
}
console.log(
  `Compiled with ${solc.version()}, evm=osaka, optimizer=200, viaIR=true. Vault runtime: ${vault.evm.deployedBytecode.object.length / 2} bytes.`,
);
